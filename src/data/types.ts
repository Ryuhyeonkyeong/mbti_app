// 유형별 3D 동물 캐릭터 정보 타입
export interface CharacterInfo {
  /** 캐릭터 동물 종류 */
  animal: string;
  /** 동물에 어울리는 캐릭터 이름 */
  name: string;
}

// 하나의 MBTI 유형에 대한 상세 설명 데이터 타입
export interface MbtiTypeInfo {
  /** 4글자 유형 코드 */
  code: MbtiTypeCode;
  /** 새로 지은 한글 별명 */
  nickname: string;
  /** 한 줄 소개 */
  summary: string;
  /** 3~4문장 분량의 성격 설명 */
  description: string;
  /** 강점 3가지 */
  strengths: [string, string, string];
  /** 조심할 점 2가지 */
  cautions: [string, string];
  /** 잘 맞는 유형 코드 2개 */
  compatibleTypes: [MbtiTypeCode, MbtiTypeCode];
  /** 파스텔 톤 대표 색상 (HEX) */
  color: string;
  /** 3D 동물 캐릭터 정보 */
  character: CharacterInfo;
}

